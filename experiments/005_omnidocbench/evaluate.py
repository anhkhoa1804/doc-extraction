"""OmniDocBench experiment, step 2 of 2: invoke the official evaluator over
predictions already generated by prepare.py.

This step runs the official OmniDocBench evaluator as an external
subprocess in its own Python 3.10/3.11 environment (.venv-omnidoc/bin/python
on Linux/macOS, .venv-omnidoc/Scripts/python.exe on Windows, by default) —
see experiments/005_omnidocbench/README.md for how that environment is set up.
This script itself still runs under the main project environment (.venv);
it does not need the evaluator's dependencies, only doc_extraction's YAML
support to write the evaluator's config file.

Independently rerunnable against existing predictions — does not regenerate
them. Useful for re-scoring with a different match method, or for running
evaluation on a machine that has the evaluator set up but didn't generate
the predictions itself (e.g. copying predictions from a Kaggle run back for
local scoring).

    python experiments/005_omnidocbench/evaluate.py \\
        --dataset experiments/005_omnidocbench/dataset/demo \\
        --output experiments/005_omnidocbench/results/baseline
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from doc_extraction.evaluation import omnidocbench as odb

_DEFAULT_OMNIDOC_PYTHON = odb.default_omnidoc_python(REPO_ROOT)


def _ground_truth_for_run(args_ground_truth: str | None, run_metadata: dict, output_root: Path) -> Path | None:
    """Resolve explicit or run-scoped truth without silently widening a subset.

    Older representative runs predate ``evaluation_ground_truth`` metadata;
    the frozen manifest marker still makes their copied subset GT authoritative.
    """
    if args_ground_truth:
        return Path(args_ground_truth).resolve()
    recorded = run_metadata.get("evaluation_ground_truth")
    if isinstance(recorded, str) and recorded:
        return output_root / recorded
    if run_metadata.get("sample_manifest_identity"):
        return output_root / "ground_truth_subset.json"
    return None


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", required=True, help="OmniDocBench dataset directory (for the ground-truth JSON).")
    parser.add_argument("--ground-truth", default=None,
                        help="Explicit selected ground-truth JSON (for a frozen subset run).")
    parser.add_argument("--output", required=True, help="Result directory containing predictions/ (from prepare.py).")
    parser.add_argument("--predictions", default=None, help="Override: predictions dir (default: <output>/predictions).")
    parser.add_argument("--omnidoc-repo", default=str(REPO_ROOT / ".external" / "OmniDocBench"))
    parser.add_argument("--omnidoc-python", default=str(_DEFAULT_OMNIDOC_PYTHON))
    parser.add_argument("--match-method", default="quick_match", choices=["no_split", "simple_match", "quick_match"])
    parser.add_argument("--match-workers", type=int, default=4,
                         help="Upstream recommends 1/3-1/2 of idle CPU cores to avoid deadlock/OOM.")
    parser.add_argument("--teds-workers", type=int, default=1,
                         help="Upstream TEDS worker count; single-worker mode avoids historical concurrent TEDS errors.")
    parser.add_argument("--include-bleu-meteor", action="store_true", help="Adds BLEU/METEOR to the text metric (slower, downloads nltk data on first use).")
    parser.add_argument("--include-cdm", action="store_true",
                         help="Adds the formula CDM metric. Needs a Linux toolchain (TeX Live + ImageMagick 7.x + "
                              "Ghostscript) the upstream project itself documents as Linux-only — do not enable "
                              "this on Windows. See docs in experiments/005_omnidocbench/README.md.")
    parser.add_argument("--timeout-seconds", type=int, default=None)
    parser.add_argument(
        "--require-pinned-evaluator", action="store_true",
        help="Require the local OmniDocBench checkout to match the adapter's pinned upstream commit.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    dataset_root = Path(args.dataset).resolve()
    output_root = Path(args.output).resolve()
    run_metadata_path = output_root / "run_metadata.json"
    run_metadata = (
        json.loads(run_metadata_path.read_text(encoding="utf-8"))
        if run_metadata_path.is_file()
        else {}
    )
    prediction_dir_name = run_metadata.get("prediction_directory", "predictions")
    predictions_dir = Path(args.predictions).resolve() if args.predictions else output_root / prediction_dir_name
    ground_truth_path = _ground_truth_for_run(args.ground_truth, run_metadata, output_root)
    omnidoc_repo = Path(args.omnidoc_repo).resolve()
    # Absolute, but NOT symlink-resolved: a venv's `bin/python` is typically a
    # symlink to the base interpreter (uv-managed installs always are), and
    # resolving it launches that base interpreter instead. The venv's
    # site-packages is then never on sys.path, so the evaluator's own
    # dependencies vanish — surfacing as `ModuleNotFoundError: No module named
    # 'yaml'` even though the venv is correctly populated. Windows hides this
    # (venvs there copy python.exe rather than symlinking it).
    omnidoc_python = Path(os.path.abspath(args.omnidoc_python))

    try:
        gt_path, samples = odb.load_dataset(dataset_root, ground_truth_path)
    except odb.DatasetError as exc:
        print(f"dataset error: {exc}", file=sys.stderr)
        return 1

    if run_metadata.get("sample_manifest_identity") and (
        run_metadata.get("run_attestation_version") == 1 or args.require_pinned_evaluator
    ):
        manifest_path = output_root / "sample_manifest.json"
        if not manifest_path.is_file():
            print("frozen-subset run is missing its copied sample_manifest.json", file=sys.stderr)
            return 1
        manifest_bytes = manifest_path.read_bytes()
        if hashlib.sha256(manifest_bytes).hexdigest() != run_metadata.get("sample_manifest_sha256"):
            print("copied benchmark manifest hash differs from run metadata", file=sys.stderr)
            return 1
        manifest = json.loads(manifest_bytes)
        if manifest.get("subset_identity", {}).get("sha256") != run_metadata.get("sample_manifest_identity"):
            print("copied manifest identity differs from run metadata", file=sys.stderr)
            return 1
        gt_bytes = gt_path.read_bytes()
        if hashlib.sha256(gt_bytes).hexdigest() != run_metadata.get("ground_truth_subset_sha256"):
            print("run-scoped ground-truth hash differs from run metadata", file=sys.stderr)
            return 1
        selected_ids = run_metadata.get("selected_page_ids")
        metadata_samples = run_metadata.get("sample_ids")
        if (
            not isinstance(selected_ids, list)
            or not isinstance(metadata_samples, list)
            or len(selected_ids) != len(samples)
            or len(metadata_samples) != len(samples)
            or len(set(selected_ids)) != len(selected_ids)
        ):
            print("run metadata selected-page coverage is invalid", file=sys.stderr)
            return 1
        loaded_ids = [f"{sample.image_name}#{sample.page_no}" for sample in samples]
        recorded_ids = [entry.get("page_id") for entry in metadata_samples]
        if loaded_ids != selected_ids or recorded_ids != selected_ids:
            print("run-scoped ground truth does not exactly match the recorded page IDs", file=sys.stderr)
            return 1

    if not predictions_dir.exists() or not any(predictions_dir.glob("*.md")):
        print(
            f"no predictions found at {predictions_dir} — run prepare.py first "
            f"(this step never generates predictions itself)",
            file=sys.stderr,
        )
        return 1
    try:
        odb.validate_prediction_alignment(samples, predictions_dir)
    except odb.PredictionAlignmentError as exc:
        print(f"prediction alignment error: {exc}", file=sys.stderr)
        return 1
    n_predictions = len(list(predictions_dir.glob("*.md")))
    print(f"ground truth: {gt_path}")
    print(f"predictions: {predictions_dir} ({n_predictions} files)")

    try:
        odb.check_evaluator_available(omnidoc_python, omnidoc_repo)
    except odb.EvaluatorNotAvailableError as exc:
        print(f"evaluator not available: {exc}", file=sys.stderr)
        return 2
    if args.require_pinned_evaluator:
        try:
            actual_revision = subprocess.run(
                ["git", "-C", str(omnidoc_repo), "rev-parse", "HEAD"],
                check=True,
                capture_output=True,
                text=True,
                timeout=5,
            ).stdout.strip()
        except (OSError, subprocess.SubprocessError) as exc:
            print(f"cannot determine evaluator checkout revision: {exc}", file=sys.stderr)
            return 2
        if actual_revision != odb.PINNED_UPSTREAM_COMMIT:
            print(
                f"evaluator revision mismatch: {actual_revision} != {odb.PINNED_UPSTREAM_COMMIT}",
                file=sys.stderr,
            )
            return 2

    config_path = odb.write_evaluator_config(
        ground_truth_path=gt_path,
        predictions_dir=predictions_dir,
        output_path=output_root / "evaluator_config.yaml",
        match_method=args.match_method,
        match_workers=args.match_workers,
        include_bleu_meteor=args.include_bleu_meteor,
        include_cdm=args.include_cdm,
    )
    print(f"evaluator config: {config_path}")
    if args.include_cdm:
        print("WARNING: --include-cdm requested; this will fail unless the TeX Live/ImageMagick/"
              "Ghostscript toolchain is present (Linux only per upstream) — see docs/backends.md-style "
              "notes in experiments/005_omnidocbench/README.md.", file=sys.stderr)
    if args.teds_workers <= 0:
        print("--teds-workers must be a positive integer", file=sys.stderr)
        return 2

    log_path = REPO_ROOT / "experiments" / "005_omnidocbench" / "logs" / f"{output_root.name}_evaluate.log"
    print(f"invoking official evaluator (log: {log_path}) ...")
    process = odb.run_official_evaluator(
        omnidoc_python=omnidoc_python,
        omnidoc_repo=omnidoc_repo,
        config_path=config_path,
        log_path=log_path,
        timeout_seconds=args.timeout_seconds,
        extra_environment={"OMNIDOCBENCH_TEDS_WORKERS": str(args.teds_workers)},
    )

    if process.returncode != 0:
        print(f"evaluator exited with code {process.returncode} — see {log_path}", file=sys.stderr)
        tail = "\n".join(process.stderr.splitlines()[-30:])
        if tail:
            print("--- last stderr lines ---", file=sys.stderr)
            print(tail, file=sys.stderr)
        return process.returncode

    save_name = f"{predictions_dir.name}_{args.match_method}"
    found = odb.collect_evaluator_results(omnidoc_repo, save_name)
    if not found:
        print(
            f"evaluator exited 0 but no result files were found for save_name={save_name!r} "
            f"under {omnidoc_repo / 'result'} — see {log_path}",
            file=sys.stderr,
        )
        return 3

    dest_names = {
        "metric_result": "metrics.json",
        "run_summary": "run_summary.json",
        "runtime_environment": "runtime_environment.json",
    }
    copied = []
    for key, src in found.items():
        dest = output_root / dest_names.get(key, src.name)
        shutil.copy2(src, dest)
        copied.append(dest)
        print(f"  {src} -> {dest}")

    metrics_path = output_root / "metrics.json"
    if metrics_path.exists():
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        print(f"metric groups reported: {list(metrics.keys())}")

    print(f"done -> {output_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
